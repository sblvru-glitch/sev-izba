/** Склонение для подписи «N фотографий» на странице работ и на главной */
export function pluralizeWorksPhotos(n: number): string {
  const mod10 = n % 10;
  const mod100 = n % 100;
  if (mod100 >= 11 && mod100 <= 14) return "фотографий";
  if (mod10 === 1) return "фотография";
  if (mod10 >= 2 && mod10 <= 4) return "фотографии";
  return "фотографий";
}
